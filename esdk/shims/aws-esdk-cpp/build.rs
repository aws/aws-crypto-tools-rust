use std::path::PathBuf;

/// Whether Cargo turned on this feature of this crate.
fn feature_on(feature: &str) -> bool {
    let var = format!("CARGO_FEATURE_{}", feature.to_uppercase().replace('-', "_"));
    std::env::var_os(var).is_some()
}

fn main() {
    // lib.rs makes `kms` stand for `kms`, `ddb` and `default-aws-sdk-clients` together.
    let hierarchical_keyring = feature_on("kms");
    let storm_tracking_cmc = hierarchical_keyring && feature_on("rt-tokio");

    // EncryptionSDK.h includes aws/esdk/Config.h, which says which optional
    // parts of the C++ API this build has, so the header always matches the library.
    // It goes next to the library, in <target>/<profile>/include,
    // because OUT_DIR is <target>/<profile>/build/<crate>-<hash>/out.
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    let include_dir = out_dir
        .ancestors()
        .nth(3)
        .expect("OUT_DIR is inside the target directory")
        .join("include");
    let config_h = include_dir.join("aws/esdk/Config.h");
    let config = format!(
        "// Generated by aws-esdk-cpp's build.rs from its Cargo features.\n\
         #pragma once\n\
         #define AWS_ESDK_CPP_HIERARCHICAL_KEYRING {}\n\
         #define AWS_ESDK_CPP_STORM_TRACKING_CMC {}\n",
        u8::from(hierarchical_keyring),
        u8::from(storm_tracking_cmc),
    );
    // Rewriting an unchanged file would make every C++ build that includes it rebuild.
    if std::fs::read_to_string(&config_h).ok().as_deref() != Some(config.as_str()) {
        std::fs::create_dir_all(config_h.parent().expect("Config.h has a parent"))
            .expect("create the Config.h directory");
        std::fs::write(&config_h, config).expect("write Config.h");
    }

    // Generates the cxx bridge code and compile it together
    // with the shim's facade into the same staticlib.
    cxx_build::bridge("src/lib.rs")
        .file("src/EncryptionSDK.cpp")
        .include("include")
        .include(&include_dir)
        .flag_if_supported("-std=c++17")
        .compile("cxxbridge-aws-mpl-cxx");
    println!("cargo:rerun-if-changed=src/lib.rs");
    println!("cargo:rerun-if-changed=src/EncryptionSDK.cpp");
    println!("cargo:rerun-if-changed=include/aws/esdk/EncryptionSDK.h");
    // A build with other features writes the same Config.h, so rewrite it when it changes.
    println!("cargo:rerun-if-changed={}", config_h.display());
}
