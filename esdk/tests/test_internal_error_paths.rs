/// Runtime-generated bytes for key/ID arguments whose value is irrelevant to
/// the validation under test.
fn random_bytes<const N: usize>() -> [u8; N] {
    let mut out = [0u8; N];
    aws_mpl_legacy::primitives::generate_random_bytes(&mut out).unwrap();
    out
}

/// Clone the static suite table entry for `binary_id` so tests can perturb
/// individual fields.
fn suite(binary_id: [u8; 2]) -> AlgorithmSuite {
    get_algorithm_suite_info(binary_id).unwrap().clone()
}

