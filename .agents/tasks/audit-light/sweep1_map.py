#!/usr/bin/env python3
"""Join extracted requirements with the hand-written rules, resolve every code anchor
by grep (regex against the real file), and write the matrix + stats.
Run from the repo root: python3 .agents/tasks/audit-light/sweep1_map.py"""
import json, re, sys, os, collections
D='.agents/tasks/audit-light/'
sys.path.insert(0,D)
from sweep1_anchors import A
rows=json.load(open(D+'sweep1-requirements.json'))
# --- resolve anchors
cache={}
def resolve(name):
    if name in cache: return cache[name]
    p,rx,n=A[name]
    lines=open(p,encoding='utf-8').read().split('\n')
    hits=[i+1 for i,l in enumerate(lines) if re.search(rx,l)]
    if len(hits)<n: raise SystemExit(f'anchor {name} unresolved')
    cache[name]=f'{p.replace("mpl/src/","").replace("prim/src/","prim:").replace("esdk/src/","esdk:")}:{hits[n-1]}'
    return cache[name]
# --- parse rules
rules={}
def parse_nums(s):
    out=[]
    for part in s.split(','):
        if '-' in part: a,b=part.split('-'); out+=range(int(a),int(b)+1)
        else: out.append(int(part))
    return out
for ln in open(D+'sweep1_rules.txt',encoding='utf-8'):
    ln=ln.rstrip('\n')
    if not ln or ln.startswith('#'): continue
    f=ln.split('|')
    assert len(f)==8,(len(f),ln)
    abbr,nums,status,anch,thr,tgt,cr,note=f
    for n in parse_nums(nums):
        key=(abbr,n)
        assert key not in rules,('dup',key)
        rules[key]=dict(status=status,anch=[] if anch=='-' else anch.split(','),thr=[] if thr=='-' else thr.split(','),tgt=[] if tgt=='-' else tgt.split(','),cr=cr,note=note)
known_threats={f'TM-MPL-{i:03d}' for i in range(1,27)}
known_targets={f'T{i:02d}' for i in range(1,27) if i!=8}|{f'C{i:02d}' for i in range(1,9) if i!=6}
out=[];stats=collections.Counter();per=collections.defaultdict(collections.Counter)
missing=[]
for r in rows:
    abbr,num=r['id'].split('-'); num=int(num)
    rule=rules.get((abbr,num))
    if rule is None: missing.append(r['id']); continue
    for t in rule['thr']: assert t in known_threats,t
    for t in rule['tgt']: assert t in known_targets,t
    if rule['status']=='B': cat='boilerplate'
    elif rule['thr'] and rule['tgt']: cat='ab'
    elif rule['thr']: cat='a'
    elif rule['tgt']: cat='b'
    else:
        cat='c'; assert rule['cr']!='-',r['id']
    locs=[resolve(a) for a in rule['anch']]
    rr=dict(r,**rule,cat=cat,locs=locs); out.append(rr)
    stats[cat]+=1; per[abbr][cat]+=1
if missing: raise SystemExit('rules missing for '+', '.join(missing))
assert len(rules)==len(rows),(len(rules),len(rows))
json.dump(out,open(D+'sweep1-matrix.json','w'),indent=1)
# --- matrix markdown
FN={'ALG':'algorithm-suites.md','STR':'structures.md','CPO':'commitment-policy.md','KRI':'keyring-interface.md','RAK':'raw-aes-keyring.md','HKR':'aws-kms/aws-kms-hierarchical-keyring.md','MRK':'aws-kms/aws-kms-mrk-match-for-decrypt.md','CMI':'cmm-interface.md','DCM':'default-cmm.md','CMC':'cryptographic-materials-cache.md','LCM':'local-cryptographic-materials-cache.md','STC':'storm-tracking-cryptographic-materials-cache.md','BKS':'branch-key-store.md'}
def esc(s): return s.replace('|','\\|')
L=['# Sweep 1: spec requirement matrix','',
 'Generated by `.agents/tasks/audit-light/sweep1_extract.py` (extraction) and `sweep1_map.py` (join with `sweep1_rules.txt`, anchor resolution by regex against the working tree at HEAD 4807e6a). Every code location below was resolved by the script; an unresolvable anchor aborts the run.','',
 'Columns: ID; spec line (`spec/framework/<file>`); keyword; requirement (truncated to 150 characters; the full text is in `sweep1-requirements.json`); status (E enforced, P partial, D documented deviation, U unenforced MUST, N not implemented in crate, X other layer or caller duty, S structural/by type, B boilerplate); code (file:line); threat; target; category (a = threat, b = target, ab = both, c = neither); for c, the reason.','',
 'c reasons: DESC descriptive sentence, no testable property. NOCODE no implementation in the crate by design (DBE, S3EC, legacy master keys, symmetric signing). ESDK implemented in `esdk/`, not in the MPL. EXT caller or external-service duty. LOWSEC implemented, fails closed or has no integrity consequence, no Verus value. NOTPROV security-relevant but not Verus-provable per the decision aid. GAP candidate gap.','']
cur=None
for r in out:
    abbr=r['id'].split('-')[0]
    if abbr!=cur:
        cur=abbr; L+=['',f'## {FN[abbr]} ({abbr})','','| ID | Line | Kw | Requirement | St | Code | Threat | Target | Cat | Reason / note |','|---|---|---|---|---|---|---|---|---|---|']
    if r['cat']=='boilerplate': continue
    txt=r['text'] if len(r['text'])<=150 else r['text'][:147]+'...'
    cr=(r['cr']+': ' if r['cat']=='c' else '')+r['note']
    L.append(f"| {r['id']} | L{r['line']} | {r['kw']} | {esc(txt)} | {r['status']} | {esc('; '.join(r['locs']) or '-')} | {', '.join(t.replace('TM-MPL-','') for t in r['thr']) or '-'} | {', '.join(r['tgt']) or '-'} | {r['cat']} | {esc(cr)} |")
open(D+'sweep1-spec-matrix.md','w',encoding='utf-8').write('\n'.join(L)+'\n')
# --- stats
tot=len(out); bo=stats['boilerplate']; ex=tot-bo
print('extracted',tot,'boilerplate',bo,'examined',ex)
print({k:v for k,v in stats.items()})
mapped=stats['a']+stats['b']+stats['ab']
print('mapped',mapped,'unmapped',stats['c'])
cr=collections.Counter(r['cr'] for r in out if r['cat']=='c'); print(cr)
st=collections.Counter(r['status'] for r in out if r['cat']!='boilerplate'); print(st)
print('per file'); 
for a,c in per.items(): print(a,dict(c))
# threats / targets referenced
th=collections.Counter(t for r in out for t in r['thr']); tg=collections.Counter(t for r in out for t in r['tgt'])
print('threats hit',len(th),sorted(th)); print('targets hit',len(tg),sorted(tg))
print('threats not hit',sorted(known_threats-set(th))); print('targets not hit',sorted(known_targets-set(tg)))
json.dump(dict(stats=stats,cr=cr,st=st,per={k:dict(v) for k,v in per.items()}),open(D+'sweep1-stats.json','w'),indent=1)
