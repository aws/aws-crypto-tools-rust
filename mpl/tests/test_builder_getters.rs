/// Set one field, check its getter sees it, clear it, check the getter is empty.
macro_rules! check {
    ($builder:expr, $set:ident, $set_opt:ident, $get:ident, $value:expr) => {{
        let builder = $builder.$set($value);
        assert!(
            builder.$get().is_some(),
            concat!(stringify!($get), " after ", stringify!($set))
        );
        let builder = builder.$set_opt(None);
        assert!(
            builder.$get().is_none(),
            concat!(stringify!($get), " after ", stringify!($set_opt))
        );
    }};
}

struct Supplier;

#[async_trait]
impl BranchKeySupplier for Supplier {
    async fn get_branch_key_id(
        &self,
        _: GetBranchKeyIdInput,
    ) -> Result<GetBranchKeyIdOutput, Error> {
        GetBranchKeyIdOutput::builder().branch_key_id("b").build()
    }
}

fn ec() -> EncryptionContext {
    EncryptionContext::new()
}

fn suite() -> AlgorithmSuiteId {
    AlgorithmSuiteId::Esdk(EsdkAlgorithmSuiteId::AlgAes256GcmHkdfSha512CommitKey)
}

fn policy() -> CommitmentPolicy {
    CommitmentPolicy::Esdk(EsdkCommitmentPolicy::RequireEncryptRequireDecrypt)
}

fn enc() -> EncryptionMaterials {
    EncryptionMaterials::builder()
        .algorithm_suite_id(suite())
        .build()
        .unwrap()
}

fn dec() -> DecryptionMaterials {
    DecryptionMaterials::builder()
        .algorithm_suite_id(suite())
        .build()
        .unwrap()
}

fn edk() -> EncryptedDataKey {
    EncryptedDataKey::builder()
        .key_provider_id("p")
        .key_provider_info(vec![1])
        .ciphertext(vec![2])
        .build()
        .unwrap()
}

fn entry() -> CacheEntry {
    let now = SystemTime::now();
    CacheEntry::builder()
        .materials(CachedMaterials::Encryption(enc()))
        .creation_time(now)
        .expiry_time(now)
        .build()
        .unwrap()
}

fn bkm() -> BranchKeyMaterials {
    BranchKeyMaterials::builder()
        .branch_key([0u8; 32])
        .branch_key_id("b")
        .branch_key_version("v")
        .encryption_context(ec())
        .build()
        .unwrap()
}

fn beacon() -> BeaconKeyMaterials {
    BeaconKeyMaterials::builder()
        .beacon_key_id("b")
        .encryption_context(ec())
        .build()
        .unwrap()
}

fn keyring() -> RawAesKeyring {
    RawAesKeyring::builder()
        .key_namespace("ns")
        .key_name("name")
        .wrapping_key(vec![0u8; 32])
        .wrapping_alg(AesWrappingAlg::AlgAes256GcmIv12Tag16)
        .build()
        .unwrap()
}

fn cache() -> LocalCmc {
    LocalCmc::builder().entry_capacity(1).build().unwrap()
}

fn sdk_config() -> aws_crypto_mpl::aws_config::SdkConfig {
    aws_crypto_mpl::aws_config::SdkConfig::builder()
        .behavior_version(aws_crypto_mpl::aws_config::BehaviorVersion::latest())
        .region(aws_crypto_mpl::aws_config::Region::new("us-west-2"))
        .build()
}

fn kms() -> KmsClient {
    KmsClient::new(&sdk_config())
}

fn ddb() -> DynamoDbClient {
    DynamoDbClient::new(&sdk_config())
}

async fn key_store() -> KeyStoreClient {
    KeyStoreClient::builder()
        .ddb_table_name("table")
        .logical_key_store_name("table")
        .kms_configuration(KmsConfiguration::KmsKeyArn(
            "arn:aws:kms:us-west-2:111122223333:key/k".into(),
        ))
        .kms_client(kms())
        .ddb_client(ddb())
        .build()
        .await
        .unwrap()
}

